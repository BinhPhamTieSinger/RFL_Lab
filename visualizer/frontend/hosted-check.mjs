import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('https://rfl-lab-visualizer.netlify.app');
await page.locator('.experiment-entry > summary').first().click();
await page.getByRole('heading',{name:'Saved evaluation table'}).waitFor();
await page.getByRole('button',{name:'Replay events'}).click();
await page.locator('.sample-images img').first().waitFor();
await page.getByRole('button',{name:'Training runs locally',exact:true}).waitFor();
await page.locator('.round-walkthrough').screenshot({path:'../docs/hosted-round.png'});
await page.setViewportSize({width:390,height:844});
await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth, undefined, {timeout: 5000});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const images=await page.locator('.sample-images img').evaluateAll(nodes=>nodes.map(n=>({width:n.naturalWidth,height:n.naturalHeight})));
await page.getByRole('button',{name:'Toggle theme'}).click();
await page.locator('.round-walkthrough').screenshot({path:'../docs/hosted-mobile.png'});
await page.getByRole('button',{name:'Experiment history',exact:true}).click();
await page.getByLabel('Search experiments').fill('plus');
await page.locator('.experiment-entry > summary').first().click();
await page.getByRole('heading',{name:'Saved evaluation table'}).waitFor();
await page.getByRole('button',{name:'Load configuration · CPU'}).click();
const device=await page.locator('label').filter({hasText:/^device/}).locator('select').inputValue();
fs.writeFileSync('../docs/hosted-verification.json',JSON.stringify({errors,mobileOverflow:overflow,images,loadedDevice:device,url:page.url()},null,2));
await browser.close();if(errors.length||overflow||device!=='cpu')process.exit(1);
