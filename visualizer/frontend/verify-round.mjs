import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
await page.getByRole('option', { name: 'FedHEP+', exact: true }).waitFor({ state: 'attached' });
await page.getByLabel('train subset', {exact: true}).fill('300');
await page.getByLabel('test subset', {exact: true}).fill('150');
await page.getByLabel('rounds', {exact: true}).fill('1');
await page.locator('summary').filter({hasText: /^attack$/i}).click();
await page.locator('label').filter({hasText:/^kind/}).locator('select').selectOption('sign_flip');
await page.getByLabel('count', {exact: true}).fill('1');
await page.getByRole('button', {name: 'Run visualization', exact: true}).click();
await page.getByText('completed', {exact: true}).first().waitFor({timeout: 120000});
await page.locator('.round-walkthrough').scrollIntoViewIfNeeded();
await page.locator('.sample-images img').first().waitFor();
const images = await page.locator('.sample-images img').evaluateAll(nodes => nodes.map(n => ({width: n.naturalWidth, height: n.naturalHeight})));
if (images.some(x => x.width !== 32 || x.height !== 32)) throw Error('Expected real 32x32 CIFAR samples');
await page.locator('.round-walkthrough').screenshot({path: '../docs/round-clients-dark.png'});
await page.getByRole('button', {name: 'Screening', exact: true}).click();
await page.locator('.round-walkthrough').screenshot({path: '../docs/round-screening.png'});
await page.getByRole('button', {name: 'Clients', exact: true}).click();
await page.getByRole('button', {name: 'Toggle theme'}).click();
await page.locator('.round-walkthrough').screenshot({path: '../docs/round-clients-light.png'});
await page.setViewportSize({width:390,height:844});
await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth, undefined, {timeout: 5000});
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await page.locator('.round-walkthrough').screenshot({path:'../docs/round-mobile.png'});
await page.getByRole('button',{name:'Experiment history',exact:true}).click();
await page.getByLabel('Search experiments').fill('plus');
await page.locator('.experiment-entry > summary').first().click();
await page.getByRole('heading',{name:'Saved evaluation table'}).first().waitFor();
await page.locator('.experiment-entry[open]').screenshot({path:'../docs/history-entry.png'});
await page.setViewportSize({width:1500,height:1000});
await page.getByRole('button',{name:'Load configuration · CPU'}).first().click();
const device = await page.locator('label').filter({hasText:/^device/}).locator('select').inputValue();
if(device !== 'cpu') throw Error('Loaded configuration must default to CPU');
fs.writeFileSync('../docs/round-verification.json', JSON.stringify({errors,images,mobileOverflow:overflow,loadedDevice:device},null,2));
await browser.close();
if(errors.length || overflow) process.exit(1);
